"""Streaming a model's answer as it is written, with the router's fallback.

`app.ai.router.ainvoke_with_fallback` waits for a whole structured response;
this yields plain text a piece at a time, for answers a learner reads as they
arrive. Fallback follows the same rules, with one difference: a model can only
be swapped for the next one BEFORE it has produced any text. Once words have
reached the learner, switching models would start a second answer under the
first, so a failure after that point ends the stream instead.
"""

from __future__ import annotations

import logging
import time
from collections.abc import AsyncIterator

from app.ai import health, quota
from app.ai.quota import is_exhausted, mark_exhausted, parse_retry_after
from app.ai.router import (
    _OUT_OF_CREDIT_COOLDOWN_SECONDS,
    _UPSTREAM_COOLDOWN_SECONDS,
    AllModelsExhausted,
    _has_key,
    _provider_of,
)
from app.ai.tasks import profile_for
from app.core.config import get_settings
from app.utils.helpers import get_llm

logger = logging.getLogger(__name__)


def _text_of(chunk) -> str:
    content = getattr(chunk, "content", "")
    if isinstance(content, str):
        return content
    return "".join(part.get("text", "") for part in content if isinstance(part, dict))


def _is_capacity(exc: BaseException) -> bool:
    """Out of credit or quota, rate-limited, too large or the provider is down:
    the same model fails the same way however the tools are offered."""
    text = str(exc).lower()
    return (quota.is_out_of_credits(exc) or quota.is_daily_quota_exhausted(exc)
            or quota.is_account_daily_cap(exc) or quota.is_upstream_unavailable(exc)
            or "rate limit" in text or "429" in text or "413" in text or "too large" in text)


def _rejects_tools(exc: BaseException) -> bool:
    """The failure is about the tools themselves -- no tool support on this
    model/endpoint, or a provider-side tool-call validation error -- not a rate
    limit, quota or outage, which a retry without tools would hit the same way."""
    text = str(exc).lower()
    return quota.is_tool_call_rejected(exc) or ("tool" in text and "rate limit" not in text)


def _set_aside(model: str, exc: BaseException, profile, chain: list[str]) -> None:
    """Marks what this failure says about `model` (and its provider)."""
    if quota.is_out_of_credits(exc):
        provider = _provider_of(model, profile)
        for other in chain:
            if _provider_of(other, profile) == provider and not other.endswith(":free"):
                mark_exhausted(other, _OUT_OF_CREDIT_COOLDOWN_SECONDS)
    elif quota.is_daily_quota_exhausted(exc) or quota.is_account_daily_cap(exc):
        mark_exhausted(model, parse_retry_after(exc) or get_settings().ai_quota_cooldown_seconds)
    elif quota.is_upstream_unavailable(exc):
        mark_exhausted(model, _UPSTREAM_COOLDOWN_SECONDS)


async def astream_with_fallback(messages: list, *, task: str, tools: list | None = None,
                                tool_choice: str | None = None, max_tokens: int | None = None) -> AsyncIterator[str | dict]:
    """Yields the answer's text as it is generated by the first model in
    `task`'s chain that starts writing.

    With `tools`, the model may also call them; each finished call is yielded
    once the model is done, as {"name", "args"}. Calls are never answered --
    the caller treats them as output, not as a step in a loop. `tool_choice`
    names one of them to force it."""
    profile = profile_for(task)
    chain = profile.chain
    usable = [model for model in chain if _has_key(model, profile)] or chain
    available = [model for model in usable if not is_exhausted(model)]
    if not available:
        raise AllModelsExhausted(f"All {profile.name} models are cooling down ({', '.join(chain)})")

    last_exc: BaseException | None = None
    # Attempts per model, most capable first. A forced tool the model will not call
    # (it writes prose; some providers then raise "tool choice is required") falls
    # back to tools offered but not forced, and any tool rejection to no tools at all:
    # a plain answer beats moving down the chain.
    attempts = [(None, None)]
    if tools:
        attempts = [(tools, None), (None, None)]
        if tool_choice:
            attempts.insert(0, (tools, tool_choice))

    last_exc: BaseException | None = None
    for model in available:
        for bound, choice in attempts:
            if is_exhausted(model):
                break
            started = False
            held: list[str] = []
            began = time.monotonic()
            gathered = None
            try:
                llm = get_llm(task, model, max_retries=0)
                if bound:
                    llm = llm.bind_tools(bound, tool_choice=choice) if choice else llm.bind_tools(bound)
                if max_tokens is not None:
                    llm = llm.bind(max_tokens=max(1, min(12000, int(max_tokens))))
                async for chunk in llm.astream(messages):
                    if bound:
                        gathered = chunk if gathered is None else gathered + chunk
                    text = _text_of(chunk)
                    if text:
                        if choice:
                            # Held until the model is done: if it refuses the forced
                            # tool, nothing has reached the learner and we can retry.
                            held.append(text)
                        else:
                            started = True
                            yield text
                calls = [c for c in (getattr(gathered, "tool_calls", None) or []) if c.get("name")]
                if choice and not calls:
                    raise RuntimeError(f"{model} did not call the forced tool {choice}")
                for piece in held:
                    started = True
                    yield piece
                for call in calls:
                    started = True
                    yield {"name": call["name"], "args": call.get("args") or {}}
                if started:
                    health.record_success(model, task, time.monotonic() - began)
                    return
                last_exc = RuntimeError(f"{model} returned no text")
                health.record_failure(model, task, last_exc, time.monotonic() - began)
                logger.warning("%s streamed no text; trying the next model", model)
                break
            except Exception as exc:  # noqa: BLE001 -- classified below
                health.record_failure(model, task, exc, time.monotonic() - began)
                if started:
                    raise
                last_exc = exc
                if choice and not _is_capacity(exc):
                    logger.info("%s would not call %s (%s); offering tools without forcing",
                                model, choice, str(exc).splitlines()[0][:160])
                    continue
                if bound and _rejects_tools(exc):
                    logger.warning("%s failed with tools (%s); retrying it without tools",
                                   model, str(exc).splitlines()[0][:160])
                    continue
                _set_aside(model, exc, profile, chain)
                logger.warning("Streaming from %s failed before any text (%s); trying the next model",
                               model, str(exc).splitlines()[0][:160])
                break
    raise AllModelsExhausted(f"No {profile.name} model could answer") from last_exc
