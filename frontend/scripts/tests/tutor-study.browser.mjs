import { existsSync } from "node:fs"
import { fileURLToPath } from "node:url"
import assert from "node:assert/strict"
import puppeteer from "puppeteer-core"
import { createServer } from "vite"
const root = fileURLToPath(new URL("../../", import.meta.url))
const executablePath = ["C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe"].find(existsSync)
const server = await createServer({ root, server: { host: "127.0.0.1", port: 0, hmr: false }, plugins: [{ name: "study-fixture", configureServer(vite) {
  vite.middlewares.use(async (req, res, next) => {
    if (!req.url.startsWith("/__study_test")) return next()
    res.setHeader("Content-Type", "text/html")
    res.end(await vite.transformIndexHtml(req.url, '<!doctype html><html><body><div id="root"></div><script type="module" src="/scripts/tests/tutor-study-fixture.jsx"></script></body></html>'))
  })
} }] })
let browser
try {
  await server.listen()
  browser = await puppeteer.launch({ executablePath, headless: true })
  const page = await browser.newPage()
  await page.setViewport({ width: 1000, height: 850 })
  await page.goto(`${server.resolvedUrls.local[0]}__study_test`)
  await page.waitForSelector('[data-tutor-study-set]')
  const outerReply = await page.$eval('[data-slot="message"][data-align="start"] [data-slot="bubble-content"]', (node) => ({border:getComputedStyle(node).borderTopWidth,shadow:getComputedStyle(node).boxShadow,padding:getComputedStyle(node).paddingTop}))
  assert.equal(outerReply.border,'0px','activity reply must not have a second outer border')
  assert.equal(outerReply.padding,'0px','activity reply must not have outer card padding')
  assert.ok(outerReply.shadow === 'none' || !outerReply.shadow.replaceAll('rgba(0, 0, 0, 0) 0px 0px 0px 0px','').replaceAll(',','').trim(),'activity reply must not have a visible outer shadow')
  const click = (text) => page.evaluate((text) => [...document.querySelectorAll("button")].find((button) => button.textContent.trim() === text).click(), text)
  assert.equal(await page.$$eval('[aria-label="Answer choices"] button', (nodes) => nodes.length), 4, "only current question is rendered")
  assert.equal(await page.$eval('a[href="/learner/library"]', (node) => node.textContent.trim()), "Saved to Library")
  await page.click('[aria-label="Answer choices"] button:nth-child(3)')
  await click("Next")
  await click("Flashcards")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /contribution per unit/)
  await click("Reveal answer")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /200/)
  await page.reload()
  await page.waitForSelector('[aria-label="Show the front"]')
  assert.equal(await page.$eval('[role="tab"][aria-selected="true"]', (node) => node.textContent), "Flashcards")
  await click("Got it")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /break-even/)
  await page.focus('[aria-label="Flip to see the answer"]')
  await page.keyboard.press("Space")
  await page.waitForSelector('[aria-label="Show the front"]')
  await click("Still learning")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /Deck reviewed/)
  await click("Review again")
  await click("Next")
  await click("Back to first")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /contribution per unit/)
  await click("Quiz")
  assert.equal(await page.$eval('[role="tabpanel"] button', (node) => node.disabled), false, "viewing a flashcard does not answer its quiz question")
  await click("Back")
  assert.equal(await page.$eval('[aria-label="Answer choices"] button:nth-child(3)', (node) => node.getAttribute("aria-pressed")), "true", "quiz answer survives toggling/reload")
  await page.screenshot({ path: "scripts/tests/tutor-study-desktop.png" })
  await page.setViewport({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await click("Flashcards")
  await click("Next")
  await click("Reveal answer")
  await click("Got it")
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /contribution per unit/, 'rating the final card wraps to the remaining unreviewed card')
  await click("Reveal answer")
  await click("Got it")
  await page.reload()
  await page.waitForSelector('[data-tutor-study-set]')
  assert.match(await page.$eval('[role="tabpanel"]', (node) => node.textContent), /Deck reviewed/)
  await page.screenshot({ path: "scripts/tests/tutor-study-mobile.png" })
  await page.click('a[href="/learner/library"]')
  assert.ok(page.url().endsWith("/learner/library"))
  console.log("PASS: paginated quiz, same-set flashcard toggle, answer/position/mode/flip persistence, confirmed Library link, responsive layout.")
} finally { await browser?.close(); await server.close() }
